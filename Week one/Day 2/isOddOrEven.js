function isOddOrEven(valueToCheck) {
   if (valueToCheck % 2 === 0)//checks number divisible by 2 
   {
      console.log(valueToCheck + " " + "is even number")//if number is divisible by 2 it prints it
   }
   else {
      console.log(valueToCheck + " " + "is odd number")//if  number is not divisible by 2 it prints it
   }
}
isOddOrEven(99)
isOddOrEven(88)